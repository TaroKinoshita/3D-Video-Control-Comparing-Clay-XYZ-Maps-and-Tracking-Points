# ---------------------------------------------------------------- Scene C' の Z 検証
# 問題：既存の Target 照合は PROBE_RGB の target_f1 のみで、コード側の
#   `if not inv and idx != 0: continue`
# により **index 0 限定**。index 0 は dZ=0 で Scene C と同一位置なので、
# B チャンネル（Z 軸）が dZ>0 のフレームで一度も照合されない。
#
# 捕まらない故障モード：
#   - B チャンネルが定数になる（dZ が反映されない）
#   - B チャンネルのスケールだけが違う
# ※ R/G/B の取り違えは target_f1 が index 0 で3チャンネル見ているので捕まる。
#
# 対策：ID パスで Target 画素を選び、その **B チャンネルの最大値**を照合する。
# Target の world Z 最大は上端 (TARGET_Z[1] + dZ) なので、どの画素が最上端かを
# 特定せずに max で拾える。上端は遮蔽板より常に上にあり隠されない。
#
# 期待値の作り方（scene_c_prime_traj.json の dZ から。閉形式）:
#   Z_top = TARGET_Z[1] + dZ = -0.10 + dZ
#   q     = clip((Z_top - NORM_BOX.z[0]) / 4.20, 0, 1)
#   level = round((0.55 + 0.40*q) * 255)          ... Target 帯 E(q)=0.55+0.40q
#
# S/N：検出すべき信号は 20 段階（177..197）に対し誤差要因は合計 0.25 段階
#   1px の Z 誤差 0.007442 unit -> 0.181 段階
#   Position パス誤差 0.0025 unit -> 0.061 段階
# よって許容は ±2 段階で十分（TOL_LEVEL の 2 倍）。
#
